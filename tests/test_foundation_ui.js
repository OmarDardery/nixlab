'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const context=vm.createContext({document:{querySelector:()=>({})},setInterval:()=>0,URL});
for(const name of ['foundation.js','operations.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../admin/static',name),'utf8'),context);
const source=fs.readFileSync(path.join(__dirname,'../admin/static/app.js'),'utf8');
vm.runInContext(source.slice(0,source.lastIndexOf('\n(async () =>')),context);
const defaults=JSON.parse(fs.readFileSync(path.join(__dirname,'fixtures/defaults.json'),'utf8'));
context.fixture=defaults;
vm.runInContext(`
state.draft=copy(fixture);
state.status={settings:copy(fixture),setupComplete:true};
state.host={interfaces:[{name:'eth0',addresses:['192.0.2.10/24']}],serialDevices:[{path:'/dev/ttyUSB0',product:'<script>bad</script>',vendorId:'1234',productId:'5678',serial:'ABC',stablePaths:['/dev/serial/by-id/example']}],helpers:{sources:{},applications:[{title:'Example',status:'upstream-supported',notes:'<img src=x>'}]}};
`,context);
let html=vm.runInContext('hostHardware()',context);
assert.ok(html.includes('&lt;script&gt;bad&lt;/script&gt;'));
assert.ok(!html.includes('<script>bad'));
assert.ok(html.includes('data-serial-pick'));
html=vm.runInContext('hostConnectivity()',context);
assert.ok(html.includes('connectivity.bridges'));
assert.ok(html.includes('connectivity.vlans'));
assert.ok(html.includes('connectivity.privateAccess'));
assert.ok(!/<button[^>]*data-(create|launch|console)-guest/.test(html),'No duplicate Incus provisioning controls');
html=vm.runInContext('integrations()',context);
assert.ok(html.includes('sudo nixlab-helpers doctor'));
assert.ok(html.includes('Upstream-supported; unverified here'));
assert.ok(html.includes('&lt;img src=x&gt;'));
assert.ok(!html.includes('data-install-script'),'No browser execution endpoint');
assert.ok(!/data-path="apps\.(cpu|memory|disk)"/.test(html),'No competing guest resource editor');
assert.ok(!vm.runInContext('operationsPage()',context).includes('data-guest-action='));
console.log('Foundation UI checks passed: ownership boundary, Ethernet/hardware forms, escaped metadata and honest compatibility.');
